dofile(PROJECT_ROOT .. "/PartyAggro335/Core.lua")
local Core = PartyAggro335Core
local count = 0
local function eq(actual, expected, name)
    count = count + 1
    assert(actual == expected, name .. ": expected " .. tostring(expected) .. ", got " .. tostring(actual))
end
local player = "player-guid"
local model = Core.New()
eq(model:Touch(nil, "Invalid", 0), nil, "reject nil GUID")
eq(model:Touch("0x0000000000000000", "Invalid", 0), nil, "reject empty GUID")
model:Touch("mob1", "Same name", 0)
model:Touch("mob2", "Same name", 0)
eq(#model:Rows(0, player), 2, "identical names remain separate")
eq(model.enemies.mob1.serial ~= model.enemies.mob2.serial, true, "stable distinct labels")
local serial = model.enemies.mob1.serial
model:Touch("mob1", "Same name", 0.2)
eq(model.enemies.mob1.serial, serial, "refresh retains label")
model:SetObservation("mob1", { threat = { status = 3, isTanking = true, percent = 100 } }, 0.2)
model:SetObservation("mob2", { threat = { status = 0, isTanking = false, percent = 61 } }, 0.2)
local rows = model:Rows(0.3, player)
eq(rows[1].guid, "mob2", "lost aggro sorts first")
eq(rows[1].status, "lost", "status zero is known lost aggro")
eq(rows[2].status, "safe", "secure native tanking")
model:SetObservation("mob1", { threat = { status = 2, isTanking = true, percent = 100 } }, 0.4)
eq(model:Rows(0.4, player)[2].status, "risk", "insecure native tanking")
rows = model:Rows(1.5, player)
eq(rows[1].status, "unknown", "expired snapshot is not shown as current")
eq(rows[1].percent, nil, "expired percentage removed")
model:SetObservation("mob1", {}, 1.5)
eq(model:Rows(1.5, player)[1].percent, nil, "missing data does not become zero")
model:SetMeleeVictim("mob1", player, "Tank", 1.5)
local row = model:Rows(1.6, player)[1]
eq(row.targetSource, "melee", "melee fallback explicitly identified")
eq(row.status, "unknown", "melee attack does not manufacture threat status")
eq(row.percent, nil, "melee attack does not manufacture percentages")
model:SetObservation("mob1", { targetName = "Healer", targetGUID = "healer",
    targetSource = "target", targetInGroup = true }, 1.7)
row = model:Rows(1.7, player)[1]
eq(row.targetName, "Healer", "current target overrides last melee victim")
eq(row.status, "lost", "known target off player is highlighted")
eq(row.percent, nil, "known target still does not manufacture percentage")
rows = model:Rows(4.1, player)
eq(rows[1].targetGUID, nil, "last victim expires")
model:Remove("mob1")
eq(#model:Rows(4.1, player), 1, "remove death")
model:Prune(30)
eq(#model:Rows(30, player), 0, "remove stale enemies")
local capped = Core.New({ maxEnemies = 2 })
capped:Touch("a", "A", 1); capped:Touch("b", "B", 2); capped:Touch("c", "C", 3)
eq(capped.enemies.a, nil, "bounded storage evicts oldest observation")
eq(#capped:Rows(3, player), 2, "bounded storage count")
capped:Clear()
eq(#capped:Rows(3, player), 0, "clear enemies")
capped:Touch("new", "New", 4)
eq(capped.enemies.new.serial, 1, "new combat restarts labels")
eq(#Core.Preview(), 4, "preview covers four statuses")
print("Core scenarios passed: " .. count)
